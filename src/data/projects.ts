/** يعيد المشروع التالي في الدوران — يُستخدم في تنقّل صفحة التفاصيل. */
export const getNextProject = (id: string): ProjectItem => {
  const idx = projects.findIndex((p) => p.id === id);
  return projects[(idx + 1) % projects.length];
};

/** يعيد المشروع السابق في الدوران. */
export const getPrevProject = (id: string): ProjectItem => {
  const idx = projects.findIndex((p) => p.id === id);
  return projects[(idx - 1 + projects.length) % projects.length];
};
