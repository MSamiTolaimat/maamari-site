/**
 * ============================================================
 * تنسيق الأرقام: صيغة لاتينية موحّدة (1، 2، 3...).
 *
 * مراجعة سابقة حوّلت كل رقم في الموقع إلى الصيغة الهندية
 * العربية (٠١، ٩٤٪). رجعنا الآن إلى الأرقام اللاتينية بطلب
 * صريح، مع إبقاء علامة النسبة المئوية اللاتينية % بدل ٪، حتى
 * لا يبقى رمز هندي وحيدًا بجانب رقم لاتيني.
 *
 * الدوال أدناه أبقت نفس الأسماء والتوقيعات التي يستدعيها بقية
 * الموقع (ar وarPercent وarOrdinal)، فلا حاجة لتعديل كل موضع
 * استدعاء — يكفي تبديل التنفيذ هنا. الاسم "ar" صار تسمية تاريخية
 * (يعني "تنسيق الأرقام" لا "الأرقام العربية")، ويُبقى عليه لتفادي
 * إعادة تسمية عشرات الاستدعاءات لتغيير لا يغيّر السلوك الظاهري
 * لغير الأرقام نفسها.
 * ============================================================
 */

/** يُعيد الرقم كما هو بصيغة لاتينية — نقطة العبور الموحّدة لكل رقم في الواجهة. */
export const ar = (value: string | number): string => String(value);

/** نسبة مئوية بصيغة لاتينية كاملة: 94% لا 94٪. */
export const arPercent = (value: number | string): string => `${ar(value)}%`;

/** ترتيب من رقمين: 1 تصبح 01. يُستخدم لتسلسل المراحل فقط. */
export const arOrdinal = (value: number): string => String(value).padStart(2, '0');
